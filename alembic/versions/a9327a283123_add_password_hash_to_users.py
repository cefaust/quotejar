"""add password_hash to users

Revision ID: a9327a283123
Revises: 0bad12f9d217
Create Date: 2026-08-06 20:31:47.592059

Adding a NOT NULL column to a table that already has rows is the classic
migration trap. Alembic's autogenerated version was:

    op.add_column('users',
        sa.Column('password_hash', sa.String(255), nullable=False))

which fails the moment `users` is non-empty, because Postgres has no value to
put in the existing rows and the column forbids NULL. It passes on an empty
development database and then breaks on production, which is the worst
possible place to find out.

The fix is to split it into three steps: add the column permissive, fill it,
then tighten the constraint.

The interesting question is what to fill it with. These accounts predate
passwords, so there is no correct value -- only safe and unsafe ones. The
tempting shortcuts are both wrong:

  - A known placeholder like hash("changeme") hands an attacker a working
    password for every legacy account.
  - An empty string is not a valid bcrypt hash, so bcrypt.checkpw raises
    ValueError("Invalid salt") instead of returning False. That turns a login
    attempt into a 500, and an endpoint that crashes on a specific account is
    itself an information leak.

So each row is backfilled with a *real* bcrypt hash of freshly generated
random bytes that are never recorded anywhere. The hash is structurally valid,
so verify_password compares against it normally and simply always returns
False. The account is unreachable by any password, including by whoever wrote
this migration.

The honest consequence: those users are locked out permanently, because
password reset is out of scope for QJ-2. In this repository the only affected
row is the fixture created by scripts/seed.py, so the cost is nil. On a real
system this step would be paired with a reset flow.
"""

