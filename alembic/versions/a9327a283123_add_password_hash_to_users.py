    # longer available at signup. Widening NOT NULL -> NULL is always safe:
    # every existing value still satisfies the looser constraint.
    op.alter_column(
        "users",
        "display_name",
        existing_type=sa.VARCHAR(length=100),
        nullable=True,
    )


