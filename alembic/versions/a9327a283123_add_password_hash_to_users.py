    # Step 1: add the column permissively so existing rows survive.
    op.add_column(
        "users", sa.Column("password_hash", sa.String(length=255), nullable=True)
    )

    # Step 2: give every existing row an unusable credential.
    #
    # Hashed per row rather than once for the whole table. One shared hash
    # would work, since the plaintext is discarded either way, but identical
    # hashes across rows advertise "these accounts share a password" to anyone
    # reading a dump -- the same property salting exists to destroy. Cheap to
    # avoid, so avoid it.
    bind = op.get_bind()
    rows = bind.execute(sa.text("SELECT id FROM users WHERE password_hash IS NULL"))
    for (user_id,) in rows.fetchall():
        unusable = bcrypt.hashpw(
            secrets.token_urlsafe(32).encode("utf-8"), bcrypt.gensalt()
        ).decode("utf-8")
        bind.execute(
            sa.text("UPDATE users SET password_hash = :h WHERE id = :id"),
            {"h": unusable, "id": user_id},
        )

    # Step 3: now that no NULLs remain, enforce the constraint.
    op.alter_column("users", "password_hash", nullable=False)

